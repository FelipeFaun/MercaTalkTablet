/**
 * Traducciones de los datos del catálogo (data/catalog.json y listas fijas de la
 * app). El catálogo se mantiene en español; aquí solo va lo que cambia en otros
 * idiomas. Lo que no está traducido se muestra tal cual (marcas, por ejemplo).
 * Se usan a través de CatalogI18nService y de los pipes productName / term.
 */
export interface RecipeTranslation {
  name: string;
  description: string;
  mainIngredient: string;
  ingredients: string[];
  steps: string[];
}

export interface CatalogTranslation {
  /** Nombre del producto por id (products.id) */
  products: Record<number, string>;
  /**
   * Textos sueltos del catálogo, con el texto en español como clave: categorías,
   * secciones, pasillos del mapa, categorías y dificultad de recetas, productos
   * de la calculadora de eventos…
   */
  terms: Record<string, string>;
  /** Unidades de cantidades armadas en el código ("2 bolsa(s)", "1 un (10 porc.)") */
  units: [RegExp, string][];
  recipes: Record<number, RecipeTranslation>;
}

